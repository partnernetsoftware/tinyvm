//! Unicode simple lowercase mapping, as sorted constant-delta runs.
//!
//! **Generated data.** Every entry is `(start, len, delta)`: the `len` code
//! points from `start` upward each lowercase to themselves plus `delta`.
//! Derived from Unicode 15 by taking every code point whose `lower()` differs
//! from itself and whose mapping is a single code point, then merging
//! neighbours that share a delta.
//!
//! # Why runs, and why this shape
//!
//! 1460 code points have a mapping; merging runs collapses them to 673,
//! because Latin Extended, Greek, Cyrillic and Armenian map by a fixed `+32`
//! or `+1`. That is the compression that makes the feature affordable at all
//! -- see `plan/design-case-mapping-decision.md`.
//!
//! The entries are a **fixed 12 bytes** in the emitted data segment (`u32`,
//! `u32`, `i32`) so a binary search can index them by multiplication. Two
//! compact encodings were measured and rejected here rather than silently:
//! `i16` deltas do **not** fit -- the range is -42561..38864, which the
//! decision document had assumed wrongly -- and an escape path for the 15
//! runs that overflow would save about 2 KB at the cost of a second lookup
//! path in hand-written wasm, where a bug is a wrong letter rather than a
//! crash. The 2 KB is named in the PRD as an option the product can ask for.
//!
//! `İ` (U+0130) is **absent**: it lowercases to two code points, and this
//! table holds single-code-point mappings only. A named divergence, criterion
//! ⑤ of the decision document.

